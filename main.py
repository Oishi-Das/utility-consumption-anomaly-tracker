"""
main.py

Runs the full utility-consumption anomaly tracker end to end:

    1. Load real electricity + raw water meter data (UNICON dataset sample)
    2. Derive WTP output / STP treated volume (synthetic extensions - see
       src/modeling.py for why, and what that means for these two numbers)
    3. Detect anomalies on all four daily series
    4. Validate the detector against known, deliberately-injected anomalies
    5. Estimate the $ cost impact of flagged spikes using example tariffs
    6. Write outputs/anomaly_report.xlsx, outputs/charts/*.png and
       outputs/summary.md

Run with:  python main.py
"""

from __future__ import annotations

import os
import pandas as pd

from src.pipeline import (
    load_interval_series,
    load_cumulative_series,
    detect_anomalies,
    estimate_cost_impact,
)
from src.modeling import derive_wtp_output, derive_stp_treated, validate_detector
from src.visualize import plot_metric_trend

DATA_DIR = "data/raw"
OUT_DIR = "outputs"
CHART_DIR = os.path.join(OUT_DIR, "charts")

# Example tariff rates only - NOT real billing rates. Replace with your
# actual utility invoices before trusting any cost figure for real decisions.
RATE_ELECTRICITY_PER_KWH = 0.28   # AUD/kWh, illustrative
RATE_WATER_PER_KL = 3.50          # AUD/kL (covers supply + sewerage), illustrative

ANOMALY_WINDOW = 14
Z_THRESHOLD = 3.0


def analyse_track(series: pd.Series, name: str, ylabel: str, rate_per_unit: float,
                   use_log: bool = False) -> dict:
    """Run detection + cost estimation + chart + validation for one metric."""
    result = detect_anomalies(series, window=ANOMALY_WINDOW, z_threshold=Z_THRESHOLD, use_log=use_log)
    result = estimate_cost_impact(result, rate_per_unit=rate_per_unit)

    safe_name = name.lower().replace(" ", "_").replace("(", "").replace(")", "")
    chart_path = os.path.join(CHART_DIR, f"{safe_name}_trend.png")
    plot_metric_trend(result, title=f"{name} - daily trend with flagged anomalies",
                       ylabel=ylabel, out_path=chart_path)

    validation = validate_detector(series, lambda s: detect_anomalies(
        s, window=ANOMALY_WINDOW, z_threshold=Z_THRESHOLD, use_log=use_log))

    n_anomalies = int(result["is_anomaly"].sum())
    total_cost = float(result["estimated_cost_impact"].sum())

    return {
        "name": name,
        "series_result": result,
        "chart_path": chart_path,
        "validation": validation,
        "n_days": len(result),
        "n_anomalies": n_anomalies,
        "total_estimated_cost_impact": round(total_cost, 2),
    }


def write_excel_report(tracks: list[dict], path: str) -> None:
    with pd.ExcelWriter(path, engine="openpyxl") as writer:
        # --- Summary sheet ---
        summary_rows = [{
            "Metric": t["name"],
            "Days analysed": t["n_days"],
            "Anomalous days flagged": t["n_anomalies"],
            "Estimated cost impact (flagged spikes)": t["total_estimated_cost_impact"],
            "Detector precision (injected test)": t["validation"]["precision"],
            "Detector recall (injected test)": t["validation"]["recall"],
        } for t in tracks]
        pd.DataFrame(summary_rows).to_excel(writer, sheet_name="Summary", index=False)

        # --- Cost-saving opportunities (ranked across all metrics) ---
        opp_frames = []
        for t in tracks:
            df = t["series_result"]
            flagged = df[(df["is_anomaly"]) & (df["estimated_cost_impact"] > 0)].copy()
            flagged["metric"] = t["name"]
            flagged = flagged.reset_index().rename(columns={"index": "date"})
            opp_frames.append(flagged[["date", "metric", "value", "rolling_mean",
                                        "excess_vs_baseline", "severity", "estimated_cost_impact"]])
        if opp_frames:
            opportunities = pd.concat(opp_frames).sort_values(
                "estimated_cost_impact", ascending=False)
            opportunities.to_excel(writer, sheet_name="Cost-Saving Opportunities", index=False)

        # --- One sheet per raw metric, full daily detail ---
        for t in tracks:
            sheet = t["name"][:31]  # Excel sheet name limit
            out = t["series_result"].reset_index().rename(columns={"index": "date"})
            out.to_excel(writer, sheet_name=sheet, index=False)


def write_summary_md(tracks: list[dict], path: str, n_meter_resets: int = 0) -> None:
    lines = ["# Run summary (auto-generated by `python main.py`)\n"]
    if n_meter_resets:
        lines.append(f"> Data-quality note: {n_meter_resets} non-monotonic water meter "
                      f"reading(s) (meter reset/replacement) were detected and excluded "
                      f"from the consumption series rather than treated as consumption.\n")
    for t in tracks:
        lines.append(f"## {t['name']}")
        lines.append(f"- Days analysed: **{t['n_days']}**")
        lines.append(f"- Anomalous days flagged: **{t['n_anomalies']}**")
        lines.append(f"- Estimated cost impact of flagged spikes: "
                      f"**${t['total_estimated_cost_impact']:,.2f}** (example tariff)")
        v = t["validation"]
        lines.append(f"- Detector validation on {v['n_injected']} deliberately-injected "
                      f"anomalies: precision **{v['precision']}**, recall **{v['recall']}**\n")
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main() -> None:
    os.makedirs(CHART_DIR, exist_ok=True)

    electricity = load_interval_series(os.path.join(DATA_DIR, "electricity_15min.csv"))
    raw_water, n_meter_resets = load_cumulative_series(
        os.path.join(DATA_DIR, "water_meter_cumulative.csv"))
    wtp_output = derive_wtp_output(raw_water)
    stp_treated = derive_stp_treated(raw_water)

    if n_meter_resets:
        print(f"Note: excluded {n_meter_resets} non-monotonic water meter reading(s) "
              f"(likely meter reset/replacement) from the consumption series.\n")

    tracks = [
        analyse_track(electricity, "Electricity Consumption", "kWh / day", RATE_ELECTRICITY_PER_KWH),
        analyse_track(raw_water, "Raw Water Consumption", "kL / day (avg rate)",
                      RATE_WATER_PER_KL, use_log=True),
        analyse_track(wtp_output, "WTP Output (modeled)", "kL / day (modeled)",
                      RATE_WATER_PER_KL, use_log=True),
        analyse_track(stp_treated, "STP Treated Volume (modeled)", "kL / day (modeled)",
                      RATE_WATER_PER_KL, use_log=True),
    ]

    write_excel_report(tracks, os.path.join(OUT_DIR, "anomaly_report.xlsx"))
    write_summary_md(tracks, os.path.join(OUT_DIR, "summary.md"), n_meter_resets)

    print("Done. Outputs written to ./outputs/\n")
    for t in tracks:
        print(f"{t['name']:32s}  days={t['n_days']:4d}  "
              f"anomalies={t['n_anomalies']:3d}  "
              f"est. cost impact=${t['total_estimated_cost_impact']:,.2f}  "
              f"detector precision/recall={t['validation']['precision']}/{t['validation']['recall']}")


if __name__ == "__main__":
    main()
